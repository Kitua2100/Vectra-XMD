import test from 'node:test';
import assert from 'node:assert/strict';
import { mkdtemp, rm } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { EventEmitter } from 'node:events';
import OwnershipStore from '../src/core/OwnershipStore.js';
import UserAuthStore from '../src/core/UserAuthStore.js';
import createMultiUserApp from '../src/app/createMultiUserApp.js';

test('end-to-end local API: login, ownership isolation, QR lifecycle, logout, restart', async t => {
  const privateDir = await mkdtemp(path.join(tmpdir(), 'vectra-phase15-'));
  let app;
  t.after(async () => { if (app) await app.shutdown(); await rm(privateDir, { recursive: true, force: true }); });
  const owners = await new OwnershipStore({ filePath: path.join(privateDir, 'session-owners.json') }).load();
  await owners.assign('alice_phone', 'alice');
  await owners.assign('bob_phone', 'bob');
  const users = await new UserAuthStore({ filePath: path.join(privateDir, 'users.json') }).load();
  await users.createUser('alice', 'Very-long-test-password-123!');
  await users.createUser('bob', 'Another-long-test-password-123!');
  const sockets = new Map();
  const socketFactory = async id => {
    const socket = { ev: new EventEmitter(), end: async () => {}, requestPairingCode: async () => '12345678', authState: { creds: { registered: false } } };
    sockets.set(id, socket);
    return socket;
  };
  app = await createMultiUserApp({ privateDir, socketFactory });
  const addr = await app.listen({ port: 0 });
  const base = `http://127.0.0.1:${addr.port}`;
  const call = (url, token, options = {}) => fetch(base + url, { ...options, headers: { ...(token ? { authorization: `Bearer ${token}` } : {}), ...(options.body ? { 'content-type': 'application/json' } : {}) } });
  const login = async (userId, password) => {
    const response = await call('/auth/login', null, { method: 'POST', body: JSON.stringify({ userId, password }) });
    assert.equal(response.status, 200);
    return (await response.json()).token;
  };
  const alice = await login('alice', 'Very-long-test-password-123!');
  const bob = await login('bob', 'Another-long-test-password-123!');
  assert.equal((await call('/sessions/bob_phone/status', alice)).status, 404);
  assert.equal((await call('/sessions/alice_phone/qr', bob)).status, 404);
  const sessions = await (await call('/sessions', alice)).json();
  assert.deepEqual(sessions.sessions.map(s => s.sessionId), ['alice_phone']);
  assert.equal((await call('/sessions/alice_phone/connect', alice, { method: 'POST' })).status, 200);
  assert.equal((await (await call('/sessions/alice_phone/status', alice)).json()).status, 'connecting');
  sockets.get('alice_phone').ev.emit('connection.update', { qr: 'mock-qr-secret' });
  assert.equal((await (await call('/sessions/alice_phone/qr', alice)).json()).qr, 'mock-qr-secret');
  assert.equal((await call('/sessions/alice_phone/qr-image', bob)).status, 404);
  sockets.get('alice_phone').ev.emit('connection.update', { connection: 'open' });
  assert.equal((await (await call('/sessions/alice_phone/status', alice)).json()).status, 'connected');
  assert.equal((await (await call('/sessions/alice_phone/qr', alice)).json()).qr, null);
  assert.equal((await call('/sessions/alice_phone/disconnect', alice, { method: 'POST' })).status, 200);
  assert.equal((await (await call('/sessions/alice_phone/status', alice)).json()).status, 'disconnected');
  assert.equal((await call('/auth/logout', alice, { method: 'POST' })).status, 200);
  assert.equal((await call('/sessions', alice)).status, 401);
  await app.shutdown();
  app = await createMultiUserApp({ privateDir, socketFactory });
  assert.equal(app.sessionManager.getSession('alice_phone').status, 'disconnected');
  assert.equal(app.accessController.getStatus('alice', 'alice_phone'), 'disconnected');
  assert.throws(() => app.accessController.getStatus('alice', 'bob_phone'), /Access denied/);
});
